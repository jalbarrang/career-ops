#!/usr/bin/env node
/**
 * regenerate-command-catalog.ts — rebuild the command catalog.
 *
 * `packages/core/src/kernel/command-catalog.ts` is what the CLI binary
 * (`packages/cli/src/bin/career-ops.ts`) and the web UI read to turn a command
 * NAME into the script that runs it. It is generated from the tree, so a file
 * that moves cannot fall out of the CLI: this script walks `packages/` and
 * records every script that is meant to be run — one with a shebang, one that
 * guards its tail with isMainModule(import.meta.url), or one wired to a
 * package.json script.
 *
 * Run after adding, renaming or moving a runnable script:
 *
 *   bun scripts/regenerate-command-catalog.ts
 */

import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join, relative, sep } from 'node:path';
import { listTree } from '../packages/core/src/kernel/walk-tree.ts';
import { repoRoot } from '../packages/core/src/kernel/repo-root.ts';

const ROOT = repoRoot(import.meta.url);
const OUT = join(ROOT, 'packages/core/src/kernel/command-catalog.ts');

const USAGE = `Usage:
  career-ops-command-catalog            # regenerate packages/core/src/kernel/command-catalog.ts
  career-ops-command-catalog --help     # show this help and exit
  career-ops-command-catalog --check    # exit 1 when the catalog is stale

A command is "runnable" when its script has a shebang, guards its tail with
isMainModule(import.meta.url), or is wired to a package.json script.`;

const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log(USAGE);
  process.exit(0);
}

/** Names wired to a package.json script. */
function packageScriptNames(): Set<string> {
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')) as { scripts?: Record<string, string> };
  const out = new Set<string>();
  for (const command of Object.values(pkg.scripts || {})) {
    for (const m of command.matchAll(/bun\s+([a-zA-Z0-9_./-]+\.ts)/g)) out.add(m[1]);
  }
  return out;
}

const fromScripts = packageScriptNames();
const commands = new Map<string, { script: string; group: string }>();
const skipped: string[] = [];

for (const abs of listTree(join(ROOT, 'packages'), { match: /\.ts$/ })) {
  const rel = relative(ROOT, abs).split(sep).join('/');
  // The dispatcher itself is not a command.
  if (rel.startsWith('packages/cli/src/bin/')) continue;
  const src = readFileSync(abs, 'utf8');
  const runnable = src.startsWith('#!') || src.includes('isMainModule(import.meta.url)') || fromScripts.has(rel);
  if (!runnable) continue;
  const name = basename(rel, '.ts');
  const groupMatch = /^packages\/(?:core|cli)\/src\/(?:commands\/)?([^/]+)\//.exec(rel);
  const group = groupMatch ? groupMatch[1] : 'misc';
  if (commands.has(name)) {
    skipped.push(`${name} (kept ${commands.get(name)!.script}, skipped ${rel})`);
    continue;
  }
  commands.set(name, { script: relative(join(ROOT, 'packages/cli/src/bin'), abs).split(sep).join('/'), group });
}

// Aliases from package.json: `bun run merge` and `career-ops merge` should
// name the same script, so a caller never has to know which spelling the CLI
// uses. An alias never overrides a real command name.
{
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')) as { scripts?: Record<string, string> };
  for (const [alias, command] of Object.entries(pkg.scripts ?? {})) {
    const m = /^bun\s+([a-zA-Z0-9_./-]+\.ts)\s*$/.exec(command.trim());
    if (!m) continue;
    const target = m[1].split('/').at(-1)!;
    const entry = [...commands.values()].find((c) => c.script.split('/').at(-1) === target);
    if (!entry || commands.has(alias)) continue;
    commands.set(alias, entry);
  }
}

const sorted = [...commands.entries()].sort(([a], [b]) => a.localeCompare(b));
const lines = sorted.map(
  ([name, e]) => `  ${JSON.stringify(name)}: { script: ${JSON.stringify(e.script)}, group: ${JSON.stringify(e.group)} },`,
);

const body = `/**
 * command-catalog.ts — command name -> runnable script.
 *
 * GENERATED by scripts/regenerate-command-catalog.ts. The CLI binary and the web
 * UI both read it, so neither can drift from the tree. Re-run the generator
 * after adding or moving a runnable script:
 *
 *   bun scripts/regenerate-command-catalog.ts
 *
 * A command is "runnable" when the script has a shebang, guards its tail with
 * isMainModule(import.meta.url), or is wired to a package.json script.
 */
export interface CommandEntry {
  /** Path to the runnable script, relative to packages/cli/src/bin. */
  script: string;
  /** Bounded context the command belongs to. */
  group: string;
}

export const COMMANDS: Record<string, CommandEntry> = {
${lines.join('\n')}
};
`;

if (argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('command-catalog.ts is stale — run: bun scripts/regenerate-command-catalog.ts');
    process.exit(1);
  }
  console.log(`command-catalog.ts is current (${commands.size} commands)`);
  process.exit(0);
}

writeFileSync(OUT, body);
// Keep the shipped copy of the catalog in step with the source in the same run
// (the updater ships packages/, so both spellings matter only if someone
// vendored one — cpSync is a no-op guard against that).
const vendored = join(ROOT, 'packages/core/src/kernel/command-catalog.generated.ts');
if (existsSync(vendored)) cpSync(OUT, vendored);

console.log(`command catalog: ${commands.size} commands written to ${relative(ROOT, OUT)}`);
if (skipped.length) console.log(`duplicate names skipped:\n  ${skipped.join('\n  ')}`);
